#!/usr/bin/env python3
"""Generates crates/zomboid-engine/src/zombie/scripting/item_params_table.rs from the decompiled
zombie.scripting.objects.Item: the script parameters whose DoParam branch is a single assignment of the value
(`this.field = Float.parseFloat(val)`, `this.field = !val.equalsIgnoreCase("true")`, ...), with each field's
declared default. Branches that do more than that are listed in COMPLEX and are not ported by this table.
  python3 tools/gen_item_params.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "decompiled/zombie/scripting/objects/Item.java").read_text()
a = src.index("   public void DoParam(String param, String val) {")
body = src[a:src.index("\n   }\n", a)]
parts = re.split(r'\} else if \(param(?:\.trim\(\))?\.equalsIgnoreCase\("([^"]+)"\)\) \{', body)
T = r'(?:\.trim\(\))?'
# (pattern, op, storage kinds the op is valid for)
PAT = [(r'^\s*this\.(\w+) = Float\.parseFloat\(val%s\);\s*$' % T, "Set", {"F32"}),
       (r'^\s*this\.(\w+) = Integer\.parseInt\(val%s\);\s*$' % T, "Set", {"I32"}),
       (r'^\s*this\.(\w+) = Integer\.parseInt\(val%s\);\s*$' % T, "IntToFloat", {"F32"}),
       (r'^\s*this\.(\w+) = val%s;\s*$' % T, "Set", {"Str"}),
       (r'^\s*this\.(\w+) = StringUtils\.discardNullOrWhitespace\(val%s\);\s*$' % T, "Discard", {"Str"}),
       (r'^\s*this\.(\w+) = val%s\.equalsIgnoreCase\("true"\);\s*$' % T, "Set", {"Bool"}),
       (r'^\s*this\.(\w+) = Boolean\.parseBoolean\(val%s\);\s*$' % T, "Set", {"Bool"}),
       (r'^\s*this\.(\w+) = !val%s\.equalsIgnoreCase\("true"\);\s*$' % T, "Not", {"Bool"})]
KIND = {"float": "F32", "int": "I32", "boolean": "Bool", "Boolean": "Bool", "String": "Str"}


def field(f):
    """(storage kind, Rust default) of a declared field, or None when it is not a plain value."""
    d = re.search(r'^\s+(?:public|private|protected)?\s*(?:final )?(float|int|boolean|Boolean|String) %s(?: = ([^;]+))?;' % f, src, re.M)
    if not d: return None
    k, init = KIND[d.group(1)], d.group(2)
    if k == "F32": dv = "0.0" if init is None else init.rstrip("Ff")
    elif k == "I32": dv = "0" if init is None else init
    elif k == "Bool": dv = ("false" if d.group(1) == "boolean" else None) if init is None else init
    else: dv = "None" if init is None or init == "null" else ("Some(%s)" % init if re.fullmatch(r'"[^"]*"', init) else None)
    if dv is None or not re.fullmatch(r'-?[\d.]+(E-?\d+)?|true|false|None|Some\("[^"]*"\)', dv): return None
    if k == "F32" and "." not in dv and "E" not in dv: dv += ".0"
    return k, dv


params, complex_, fields = [], [], {}
for i in range(1, len(parts), 2):
    name, code = parts[i], parts[i + 1]
    done = False
    for p, op, kinds in PAT:
        m = re.match(p, code, re.S)
        if not m: continue
        fd = field(m.group(1))
        if fd is None or fd[0] not in kinds: continue
        fields[m.group(1)] = fd
        params.append((name.lower(), m.group(1), op))
        done = True
        break
    if not done: complex_.append(name)
order = list(fields)
out = ["//! Generated by tools/gen_item_params.py from zombie.scripting.objects.Item.DoParam. Do not edit.",
       "use super::item::{FieldDef, FieldValue as V, Op};", "",
       "/// Fields set by single-assignment branches, with their declared defaults.",
       "#[rustfmt::skip]", "pub const FIELDS: [FieldDef; %d] = [" % len(order)]
for f in order:
    k, dv = fields[f]
    v = {"F32": "V::F32(%s)", "I32": "V::I32(%s)", "Bool": "V::Bool(%s)", "Str": "V::Str(%s)"}[k] % dv
    out.append('    FieldDef { name: "%s", default: %s },' % (f, v))
out += ["];", "", "/// Script parameter (lower case) -> (index into FIELDS, how the value is assigned).",
        "#[rustfmt::skip]", "pub const PARAMS: [(&str, usize, Op); %d] = [" % len(params)]
out += ['    ("%s", %d, Op::%s),' % (n, order.index(f), op) for n, f, op in params]
out += ["];", "", "/// Parameters whose DoParam branch does more than a single assignment; not handled by this table.", "#[rustfmt::skip]", "pub const COMPLEX: [&str; %d] = [" % len(complex_)]
out += ['    "%s",' % c.lower() for c in complex_] + ["];", ""]
(root / "crates/zomboid-engine/src/zombie/scripting/item_params_table.rs").write_text("\n".join(out))
(root / "target/oracle").mkdir(parents=True, exist_ok=True)
# The fields the oracle compares. aimingMod is left out: Item.InstanceItem writes HandWeapon's constant 1.0 back into
# the script, and the server's Lua (forageSystem.isItemScriptValid) instances every forage item before the probe runs.
(root / "target/oracle/item_fields.txt").write_text("\n".join(f for f in order if f != "aimingMod") + "\n")
print(len(params), "params,", len(order), "fields,", len(complex_), "complex")
