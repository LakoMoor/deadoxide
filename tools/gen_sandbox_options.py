#!/usr/bin/env python3
"""Generates crates/zomboid-engine/src/zombie/sandbox_options_table.rs from the decompiled zombie.SandboxOptions:
every option in registration order (field order, nested groups where their field is declared).
  python3 tools/gen_sandbox_options.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "decompiled/zombie/SandboxOptions.java").read_text()
ENUMS = {"InjurySeverity": ["LOW", "NORMAL", "HIGH"], "DamageModifier": ["NONE", "LOW", "STANDARD", "HIGH", "EXTREME"]}
CALL = re.compile(r'new(Boolean|Double|Enum|Integer|String)Option\(\s*"([^"]+)",\s*(.*?)\)\s*(?:\.set\w+\([^)]*\)\s*)*;', re.S)
def options(text):
    out = []
    for m in CALL.finditer(text):
        kind, name = m.group(1), m.group(2)
        if kind == "String":
            lit = re.match(r'\s*("(?:[^"\\]|\\.)*")\s*,\s*(.*)', m.group(3), re.S)
            args = [lit.group(1), lit.group(2).strip()]
        else:
            args = [a.strip() for a in m.group(3).split(",")]
        out.append((m.start(), kind, name, args))
    return out
def class_body(name):
    i = src.index("public final class %s {" % name)
    depth, j = 0, src.index("{", i)
    k = j
    while True:
        if src[k] == "{": depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0: return src[j:k]
        k += 1
groups = {g: class_body(g) for g in ["Basement", "Map", "ZombieLore", "ZombieConfig", "MultiplierConfig"]}
top_end = src.index("public final class Basement {")
# top-level fields end before the first method; nested group fields are declared among them
items = [(pos, ("opt", kind, name, args)) for pos, kind, name, args in options(src[:top_end])]
for m in re.finditer(r'new SandboxOptions\.(Basement|Map|ZombieLore|ZombieConfig|MultiplierConfig)\(\)', src[:top_end]):
    items.append((m.start(), ("group", m.group(1))))
items.sort()
rows = []
def num(s):
    s = s.replace("Integer.MAX_VALUE", "2147483647").replace("Integer.MIN_VALUE", "-2147483648").replace("Double.MAX_VALUE", "f64::MAX")
    return s.rstrip("FfDdL")
def add(kind, name, args):
    if kind == "Boolean": rows.append('    Def { name: "%s", kind: Kind::Boolean(%s) },' % (name, args[0]))
    elif kind == "Double":
        f = lambda a: a if "MAX" in a else (num(a) if any(c in num(a) for c in ".eE") else num(a) + ".0")
        rows.append('    Def { name: "%s", kind: Kind::Double { min: %s, max: %s, default: %s } },' % (name, f(num(args[0])), f(num(args[1])), f(num(args[2]))))
    elif kind == "Integer": rows.append('    Def { name: "%s", kind: Kind::Integer { min: %s, max: %s, default: %s } },' % (name, num(args[0]), num(args[1]), num(args[2])))
    elif kind == "Enum":
        if args[0].endswith(".class"):
            e = ENUMS[args[0][:-6]]
            rows.append('    Def { name: "%s", kind: Kind::Enum { num_values: %d, default: %d } },' % (name, len(e), e.index(args[1].split(".")[1]) + 1))
        else: rows.append('    Def { name: "%s", kind: Kind::Enum { num_values: %s, default: %s } },' % (name, num(args[0]), num(args[1])))
    elif kind == "String": rows.append('    Def { name: "%s", kind: Kind::Str { default: %s, max_length: %s } },' % (name, args[0], num(args[1])))
for _, it in items:
    if it[0] == "opt": add(*it[1:])
    else:
        for _, kind, name, args in options(groups[it[1]]): add(kind, name, args)
out = "//! Generated by tools/gen_sandbox_options.py from zombie.SandboxOptions (registration order). Do not edit.\nuse super::sandbox_options::{Def, Kind};\n\npub const OPTIONS: [Def; %d] = [\n%s\n];\n" % (len(rows), "\n".join(rows))
(root / "crates/zomboid-engine/src/zombie/sandbox_options_table.rs").write_text(out)
print(len(rows), "options")
