// Class ledger: which of the game's Java classes the Rust code follows, derived from the code itself.
// Input 1: ./decompiled (sh tools/decompile.sh) -> every class with its line and method count.
// Input 2: Rust doc comments that open with the Java symbol they port ("/// zombie.iso.LotHeader.load: ...").
// Output: docs/CLASS_LEDGER.md (per-package table + cited classes). "Cited" means some method is ported, NOT that the class is complete.
//   node tools/class_ledger.mjs
import fs from "node:fs";
import path from "node:path";

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const dec = path.join(repo, "decompiled");
if (!fs.existsSync(dec)) throw new Error("no ./decompiled; run sh tools/decompile.sh");

const walk = (d, ext, out = []) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (e.name !== "target" && e.name !== "META-INF") walk(p, ext, out); }
    else if (e.name.endsWith(ext)) out.push(p);
  }
  return out;
};

// A method/constructor declaration line as Vineflower prints it: modifiers, a return type or nothing, name(args) {
const METHOD = /^\s+(?:(?:public|protected|private|static|final|synchronized|native|abstract|default)\s+)*(?:<[^>]+>\s+)?(?:[\w.$<>\[\],? ]+\s+)?(\w+)\s*\([^;]*\)\s*(?:throws [\w., ]+)?\s*\{\s*$/;
const KEYWORDS = new Set(["if", "for", "while", "switch", "catch", "synchronized", "try", "else", "do", "return", "new"]);
const classes = new Map();
for (const f of walk(dec, ".java")) {
  const fq = path.relative(dec, f).replace(/\.java$/, "").split(path.sep).join(".");
  const lines = fs.readFileSync(f, "utf8").split("\n");
  const methods = new Set();
  for (const l of lines) { const m = METHOD.exec(l); if (m && !KEYWORDS.has(m[1])) methods.add(m[1]); }
  classes.set(fq, { lines: lines.length, methods, cited: new Set(), where: new Set(), text: lines.join("\n") });
}

const CITE = /\/\/[\/!]?\s*((?:zombie|se\.krka|fmod|generation|astar|N3D)\.[A-Za-z0-9_.$]+)/g;
let unknown = new Set();
for (const dir of ["crates", "launcher"]) {
  for (const f of walk(path.join(repo, dir), ".rs")) {
    const rel = path.relative(repo, f).split(path.sep).join("/");
    for (const m of fs.readFileSync(f, "utf8").matchAll(CITE)) {
      const sym = m[1].replace(/\.$/, "");
      // Longest class prefix; the remainder (if any) is the method.
      let cls = sym, method = null;
      while (cls && !classes.has(cls)) { const i = cls.lastIndexOf("."); method = cls.slice(i + 1); cls = i < 0 ? "" : cls.slice(0, i); }
      if (!cls) { unknown.add(sym + " (" + rel + ")"); continue; }
      const c = classes.get(cls);
      if (method && cls !== sym) {
        // Fields, constants and inner classes are accepted when the name occurs in the class; only methods are counted.
        const rest = sym.slice(cls.length + 1).split(".");
        if (!rest.every((w) => new RegExp("\\b" + w + "\\b").test(c.text))) { unknown.add(sym + " (" + rel + ")"); continue; }
        if (rest.length === 1 && c.methods.has(method)) c.cited.add(method); else c.cited.add("*");
      } else c.cited.add("*");
      c.where.add(rel);
    }
  }
}

const pkgOf = (fq) => { const p = fq.split("."); return p[0] === "zombie" ? p.slice(0, Math.min(2, p.length - 1)).join(".") : p[0]; };
const pk = new Map();
let tot = { n: 0, lines: 0, methods: 0, cn: 0, cm: 0 };
for (const [fq, c] of classes) {
  const k = pkgOf(fq);
  const a = pk.get(k) ?? { n: 0, lines: 0, methods: 0, cn: 0, cm: 0 };
  const cm = [...c.cited].filter((x) => x !== "*").length;
  for (const t of [a, tot]) { t.n++; t.lines += c.lines; t.methods += c.methods.size; if (c.cited.size) t.cn++; t.cm += cm; }
  pk.set(k, a);
}
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : "0.0") + "%";
const lock = JSON.parse(fs.readFileSync(path.join(repo, "reference.lock.json"), "utf8"));
let md = `# Class ledger (generated by tools/class_ledger.mjs, do not edit)\n\n`;
md += `Source: decompiled \`${lock.jar}\` sha256 \`${lock.jar_sha256.toLowerCase()}\` (build ${lock.steam_buildid}), game-owned packages only.\n`;
md += `A method counts as cited when a Rust doc comment names it. Citing is a pointer for reviewers, not proof of parity: evidence lives in docs/COMPATIBILITY.md.\n`;
md += `Method counts are distinct method names per top-level file (overloads and inner classes merged).\n\n`;
md += `**Total: ${tot.cn} of ${tot.n} classes touched, ${tot.cm} of ${tot.methods} method names cited (${pct(tot.cm, tot.methods)}), ${tot.lines} decompiled lines.**\n\n`;
md += `| Package | Classes | Touched | Method names | Cited | Lines |\n|---|---:|---:|---:|---:|---:|\n`;
for (const [k, a] of [...pk].sort((x, y) => y[1].lines - x[1].lines)) md += `| ${k} | ${a.n} | ${a.cn} | ${a.methods} | ${a.cm} (${pct(a.cm, a.methods)}) | ${a.lines} |\n`;
md += `\n## Touched classes\n\n| Class | Cited / method names | Rust |\n|---|---:|---|\n`;
for (const [fq, c] of [...classes].filter((x) => x[1].cited.size).sort()) {
  const cm = [...c.cited].filter((x) => x !== "*").length;
  md += `| ${fq} | ${cm} / ${c.methods.size} | ${[...c.where].sort().join(", ")} |\n`;
}
if (unknown.size) md += `\n## Citations that match no decompiled class or method (fix the comment)\n\n${[...unknown].sort().map((s) => "- " + s).join("\n")}\n`;
fs.writeFileSync(path.join(repo, "docs", "CLASS_LEDGER.md"), md);
console.log(`classes ${tot.cn}/${tot.n} touched, methods ${tot.cm}/${tot.methods} cited, unknown citations ${unknown.size}`);
